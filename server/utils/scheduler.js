const cron = require("node-cron");
const crypto = require("crypto");
const Department = require("../models/Department");
const Session = require("../models/Session");
const { todayKey } = require("./dayKey");
const { findDaySession } = require("./daySessions");

const QR_VALID_MINUTES = 10;
const DAY_ABBR = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"];

// Runs every tick: creates a session for any schedule block starting now
async function generateDueSessions() {
  const now = new Date();
  const todayAbbr = DAY_ABBR[now.getDay()];
  const currentHHMM = `${String(now.getHours()).padStart(2, "0")}:${String(
    now.getMinutes()
  ).padStart(2, "0")}`;

  const departments = await Department.find({});

  for (const dept of departments) {
    const dueBlock = (dept.schedule || []).find(
      (b) => b.day === todayAbbr && b.startTime === currentHHMM
    );
    if (!dueBlock) continue;

    // One session per department per day
    const existing = await findDaySession(dept._id, todayKey());
    if (existing) continue;

    await Session.create({
      department: dept._id,
      date: now,
      dayKey: todayKey(),
      qrToken: crypto.randomBytes(16).toString("hex"),
      qrExpiresAt: new Date(now.getTime() + QR_VALID_MINUTES * 60 * 1000),
      autoGenerated: true,
      scheduleStartTime: dueBlock.startTime,
    });

    console.log(`[scheduler] Auto-created session for "${dept.name}" at ${dueBlock.startTime}`);
  }
}

// Runs on startup: creates sessions that should have been created today
async function catchUpMissedSessions() {
  const now = new Date();
  const todayAbbr = DAY_ABBR[now.getDay()];
  const currentHHMM = `${String(now.getHours()).padStart(2, "0")}:${String(
    now.getMinutes()
  ).padStart(2, "0")}`;

  const departments = await Department.find({});

  for (const dept of departments) {
    // Use the earliest block of today
    const dueTodayBlocks = (dept.schedule || [])
      .filter((b) => b.day === todayAbbr && b.startTime <= currentHHMM)
      .sort((a, b) => a.startTime.localeCompare(b.startTime))
      .slice(0, 1);

    for (const block of dueTodayBlocks) {
      const existing = await findDaySession(dept._id, todayKey());
      if (existing) continue;

      const scheduledDate = new Date(now);
      const [h, m] = block.startTime.split(":").map(Number);
      scheduledDate.setHours(h, m, 0, 0);

      await Session.create({
        department: dept._id,
        date: scheduledDate,
        dayKey: todayKey(),
        qrToken: crypto.randomBytes(16).toString("hex"),
        qrExpiresAt: new Date(scheduledDate.getTime() + QR_VALID_MINUTES * 60 * 1000),
        autoGenerated: true,
        scheduleStartTime: block.startTime,
      });

      console.log(
        `[scheduler] Caught up a missed session for "${dept.name}" at ${block.startTime} (server was likely down when it was due)`
      );
    }
  }
}

function startScheduler() {
  // Catch up once on startup
  catchUpMissedSessions().catch((err) =>
    console.error("[scheduler] catch-up error:", err.message)
  );

  // Check every minute
  cron.schedule("* * * * *", () => {
    generateDueSessions().catch((err) => console.error("[scheduler] error:", err.message));
  });
  console.log("[scheduler] Recurring session generator started");
}

module.exports = { startScheduler, generateDueSessions, catchUpMissedSessions };
