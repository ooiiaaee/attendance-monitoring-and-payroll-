const mongoose = require("mongoose");

const sessionSchema = new mongoose.Schema(
  {
    department: { type: mongoose.Schema.Types.ObjectId, ref: "Department", required: true },
    date: { type: Date, default: Date.now },
    // Calendar day of the session, "YYYY-MM-DD"; one session per department per day
    dayKey: { type: String, default: null },
    qrToken: { type: String, required: true, unique: true },
    qrExpiresAt: { type: Date, required: true },
    // Manager's location when the session was started
    location: {
      lat: { type: Number, default: null },
      lng: { type: Number, default: null },
    },
    // True if created automatically from the department schedule
    autoGenerated: { type: Boolean, default: false },
    // Start time of the schedule block this session was generated for
    scheduleStartTime: { type: String, default: null },
    // Soft delete flag
    isActive: { type: Boolean, default: true },
  },
  { timestamps: true }
);

sessionSchema.index({ department: 1, dayKey: 1 });

module.exports = mongoose.model("Session", sessionSchema);
