import { useState } from "react";
import { useNavigate, Link } from "react-router-dom";
import { useAuth } from "../context/AuthContext";
import {
  validateEmail,
  validatePassword,
  validateConfirmPassword,
  validateName,
} from "../utils/validators";
import logoImg from "../assets/kajalogo.png";
import "../styles/shared.css";
import "./Auth.css";

export default function Register() {
  const [name, setName] = useState("");
  const [email, setEmail] = useState("");
  const [password, setPassword] = useState("");
  const [confirmPassword, setConfirmPassword] = useState("");
  const [role, setRole] = useState("staff");
  const [fieldErrors, setFieldErrors] = useState({});
  const [serverError, setServerError] = useState("");
  const [submitting, setSubmitting] = useState(false);
  const [pendingMessage, setPendingMessage] = useState("");
  const { register } = useAuth();
  const navigate = useNavigate();

  const validate = () => {
    const errors = {
      name: validateName(name),
      email: validateEmail(email),
      password: validatePassword(password),
      confirmPassword: validateConfirmPassword(password, confirmPassword),
    };
    setFieldErrors(errors);
    return !Object.values(errors).some(Boolean);
  };

  const handleSubmit = async (e) => {
    e.preventDefault();
    setServerError("");
    setPendingMessage("");
    if (!validate()) return;

    setSubmitting(true);
    try {
      // The Staff ID is generated by the server
      const result = await register(name, email, password, role);

      if (result.pendingApproval) {
        setPendingMessage(result.message);
      } else {
        navigate("/dashboard");
      }
    } catch (err) {
      setServerError(err.response?.data?.message || "Registration failed. Please try again.");
    } finally {
      setSubmitting(false);
    }
  };

  return (
    <div className="auth-page">
      <div className="auth-glass-card">
        
        {/* Left panel */}
        <div className="auth-sidebar-panel">
          <div className="sidebar-content">
            <h2>Welcome Back!</h2>
            <p>To keep connected with us please login with your personal info</p>
            <Link to="/login">
              <button type="button" className="btn-toggle-switch">
                SIGN IN
              </button>
            </Link>
          </div>
        </div>

        {/* Form */}
        <div className="auth-form-content">
          <div className="auth-logo-container">
            <img src={logoImg} alt="KAJA Logo" className="auth-logo-img" />
            <span className="auth-brand-name">KAJA</span>
          </div>

          {pendingMessage ? (
            <>
              <h1>ALMOST THERE</h1>
              <div className="banner banner-success" style={{ marginTop: "16px" }}>
                {pendingMessage}
              </div>
              <div className="auth-switch" style={{ marginTop: "20px" }}>
                <Link to="/login">Back to sign in</Link>
              </div>
            </>
          ) : (
            <>
              <h1>SIGN UP</h1>

              {serverError && <div className="banner banner-error">{serverError}</div>}

              <form onSubmit={handleSubmit} noValidate>
                <div className="auth-field">
                  <label className="field-label" htmlFor="name">Full Name</label>
                  <input
                    id="name"
                    className="field-input"
                    placeholder="Full Name"
                    value={name}
                    onChange={(e) => setName(e.target.value)}
                    onBlur={() => setFieldErrors((f) => ({ ...f, name: validateName(name) }))}
                  />
                  {fieldErrors.name && <span className="field-error">{fieldErrors.name}</span>}
                </div>

                <div className="auth-field">
                  <label className="field-label" htmlFor="email">Email</label>
                  <input
                    id="email"
                    type="email"
                    className="field-input"
                    placeholder="Email"
                    value={email}
                    onChange={(e) => setEmail(e.target.value)}
                    onBlur={() => setFieldErrors((f) => ({ ...f, email: validateEmail(email) }))}
                  />
                  {fieldErrors.email && <span className="field-error">{fieldErrors.email}</span>}
                </div>

                <div className="auth-field">
                  <label className="field-label" htmlFor="password">Password</label>
                  <input
                    id="password"
                    type="password"
                    className="field-input"
                    placeholder="Password"
                    value={password}
                    onChange={(e) => setPassword(e.target.value)}
                    onBlur={() =>
                      setFieldErrors((f) => ({ ...f, password: validatePassword(password) }))
                    }
                  />
                  {fieldErrors.password && (
                    <span className="field-error">{fieldErrors.password}</span>
                  )}
                </div>

                <div className="auth-field">
                  <label className="field-label" htmlFor="confirmPassword">Confirm Password</label>
                  <input
                    id="confirmPassword"
                    type="password"
                    className="field-input"
                    placeholder="Confirm Password"
                    value={confirmPassword}
                    onChange={(e) => setConfirmPassword(e.target.value)}
                    onBlur={() =>
                      setFieldErrors((f) => ({
                        ...f,
                        confirmPassword: validateConfirmPassword(password, confirmPassword),
                      }))
                    }
                  />
                  {fieldErrors.confirmPassword && (
                    <span className="field-error">{fieldErrors.confirmPassword}</span>
                  )}
                </div>

                <div className="auth-field">
                  <label className="field-label" htmlFor="role">Role</label>
                  <select
                    id="role"
                    className="field-input"
                    value={role}
                    onChange={(e) => setRole(e.target.value)}
                  >
                    <option value="staff">Staff</option>
                    <option value="manager">Manager</option>
                  </select>
                  {role === "manager" && (
                    <p className="auth-role-note">
                      Manager accounts require HR admin approval before you can log in.
                    </p>
                  )}
                </div>

                {role === "staff" && (
                  <p className="auth-role-note">
                    A Staff ID is generated for you automatically — you'll find it on your profile
                    page after signing up.
                  </p>
                )}

                <button
                  className="btn btn-primary"
                  type="submit"
                  disabled={submitting}
                >
                  {submitting ? "Creating account..." : "REGISTER"}
                </button>
              </form>
            </>
          )}
        </div>

      </div>
    </div>
  );
}